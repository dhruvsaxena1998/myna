//! The decision provider: yes/no questions answered by a small model (Laya on this Mac, Jev, OpenAI Decisions or any
//! server that speaks one of those two wire formats). Used by the experimental muted-segment triage.
use crate::{
    ai::{self, keychain},
    laya, settings, Db,
};
use serde::Serialize;
use serde_json::{json, Value};
use std::{sync::Mutex, time::Duration};
use tauri::{AppHandle, Manager};
use url::Url;

pub trait DecisionProvider: Send + Sync {
    /// Whether the answer to `question`, given `context`, is yes. Err when the provider could not answer.
    fn decide(&self, question: &str, context: &str) -> Result<bool, String>;
}

#[derive(Clone, Copy, PartialEq, Debug, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Wire {
    Jev,
    Openai,
}

#[derive(Serialize)]
pub struct Preset {
    pub id: &'static str,
    pub name: &'static str,
    pub base_url: &'static str,
    pub wire: Wire,
    /// Placeholder for the model field, which only the OpenAI wire has.
    pub model: &'static str,
}

pub const PRESETS: &[Preset] = &[
    // Laya's address is its own: the managed sidecar picks the port.
    Preset { id: "laya", name: "Laya", base_url: "", wire: Wire::Jev, model: "" },
    // shortcut: the Jev and OpenAI Decisions endpoints and body shapes below are written from the spec, not from
    // the providers' docs; check both against a real account before relying on them.
    Preset { id: "jev", name: "Jev", base_url: "https://api.jev.ai/v1", wire: Wire::Jev, model: "" },
    Preset { id: "openai", name: "OpenAI Decisions", base_url: "https://api.openai.com/v1", wire: Wire::Openai, model: "gpt-5-mini" },
    Preset { id: "custom", name: "Custom", base_url: "http://localhost:8000/v1", wire: Wire::Jev, model: "" },
];

fn preset(id: Option<&str>) -> &'static Preset {
    PRESETS.iter().find(|p| Some(p.id) == id).unwrap_or(&PRESETS[0])
}

fn account(preset: &str) -> String {
    format!("decision-{preset}")
}

#[derive(Clone)]
pub struct Config {
    pub preset: &'static Preset,
    pub wire: Wire,
    pub base_url: String,
    pub model: String,
    /// Laya's key is generated by Myna, so it is not here.
    pub key: Option<String>,
}

impl Config {
    pub fn from_settings(db: &rusqlite::Connection) -> Config {
        let preset = preset(settings::get(db, "decision_preset").as_deref());
        let wire = match (preset.id, settings::get(db, "decision_wire").as_deref()) {
            ("custom", Some("openai")) => Wire::Openai,
            _ => preset.wire,
        };
        Config {
            preset,
            wire,
            base_url: settings::get(db, "decision_base_url").filter(|u| !u.trim().is_empty()).unwrap_or(preset.base_url.into()),
            model: settings::get(db, "decision_model").unwrap_or_default().trim().to_string(),
            key: None,
        }
    }

    /// Settings under the lock, then the Keychain outside it.
    pub fn load(db: &Mutex<rusqlite::Connection>) -> Config {
        let mut c = Config::from_settings(&db.lock().unwrap());
        c.key = keychain::get(&account(c.preset.id));
        c
    }

    /// Why a question cannot be asked yet, in words for the user.
    pub fn problem(&self, laya_installed: bool) -> Option<&'static str> {
        if self.preset.id == "laya" {
            (!laya_installed).then_some("Set up Laya under Decision provider in Settings.")
        } else if !matches!(Url::parse(&self.base_url), Ok(u) if matches!(u.scheme(), "http" | "https") && u.host().is_some()) {
            Some("The base URL under Decision provider in Settings is not valid.")
        } else if self.wire == Wire::Openai && self.model.is_empty() {
            Some("Add a model name under Decision provider in Settings.")
        } else if self.key.is_none() && self.preset.id != "custom" {
            Some("Add an API key under Decision provider in Settings.")
        } else {
            None
        }
    }

    /// Whether a question would leave this Mac: never for Laya, whose server is on loopback.
    pub fn off_device(&self) -> bool {
        self.preset.id != "laya" && ai::is_off_device(&self.base_url)
    }
}

/// The adapter for `wire`, talking to `base_url`.
pub fn adapter(wire: Wire, base_url: &str, key: Option<String>, model: &str) -> Box<dyn DecisionProvider> {
    let base = base_url.trim_end_matches('/').to_string();
    match wire {
        Wire::Jev => Box::new(Jev { base, key }),
        Wire::Openai => Box::new(OpenAiDecisions { base, key, model: model.into() }),
    }
}

fn post(url: &str, key: Option<&str>, body: Value) -> Result<Value, String> {
    let agent = ureq::AgentBuilder::new().timeout_connect(Duration::from_secs(10)).timeout(Duration::from_secs(30)).build();
    let mut req = agent.post(url);
    if let Some(key) = key {
        req = req.set("Authorization", &format!("Bearer {key}"));
    }
    match req.send_json(body) {
        Ok(r) => r.into_json().map_err(|e| format!("The decision provider's reply was not JSON: {e}")),
        Err(ureq::Error::Status(code, r)) => {
            let body: Value = r.into_json().unwrap_or_default();
            let said = body["error"]["message"].as_str().or(body["error"].as_str()).unwrap_or("no details");
            Err(format!("The decision provider answered {code}: {said}"))
        }
        Err(e) => Err(format!("Could not reach the decision provider: {e}")),
    }
}

/// "yes" or "no" (any case), or a JSON boolean. Anything else is not an answer.
fn yes_no(v: &Value) -> Result<bool, String> {
    match v {
        Value::Bool(b) => Ok(*b),
        Value::String(s) if s.trim().eq_ignore_ascii_case("yes") => Ok(true),
        Value::String(s) if s.trim().eq_ignore_ascii_case("no") => Ok(false),
        _ => Err("The decision provider's answer was not yes or no.".into()),
    }
}

const CHOICES: [&str; 2] = ["yes", "no"];

/// Jev, Laya and custom servers: `POST {base}/decide`.
struct Jev {
    base: String,
    key: Option<String>,
}

impl DecisionProvider for Jev {
    fn decide(&self, question: &str, context: &str) -> Result<bool, String> {
        let reply = post(&format!("{}/decide", self.base), self.key.as_deref(), json!({"question": question, "context": context, "choices": CHOICES}))?;
        yes_no(&reply["choice"])
    }
}

/// OpenAI Decisions: `POST {base}/decisions`, one input and the model.
struct OpenAiDecisions {
    base: String,
    key: Option<String>,
    model: String,
}

impl DecisionProvider for OpenAiDecisions {
    fn decide(&self, question: &str, context: &str) -> Result<bool, String> {
        let body = json!({"model": self.model, "input": format!("{question}\n\n{context}"), "choices": CHOICES});
        yes_no(&post(&format!("{}/decisions", self.base), self.key.as_deref(), body)?["decision"]["choice"])
    }
}

/// The provider triage asks, or None when triage is off or the provider is not ready (said on stderr). Starts Laya when
/// that is the preset, which can take a while.
pub fn for_triage(app: &AppHandle) -> Option<Box<dyn DecisionProvider>> {
    let db = &app.state::<Db>().0;
    if !ai::enabled(&db.lock().unwrap(), "triage") {
        return None;
    }
    let c = Config::load(db);
    let laya = app.state::<laya::Laya>();
    if let Some(problem) = c.problem(laya.installed()) {
        eprintln!("Triage skipped: {problem}");
        return None;
    }
    if c.preset.id == "laya" {
        return match laya.serve(&account("laya")) {
            Ok((url, key)) => Some(adapter(Wire::Jev, &url, Some(key), "")),
            Err(e) => {
                eprintln!("Triage skipped: {e}");
                None
            }
        };
    }
    Some(adapter(c.wire, &c.base_url, c.key, &c.model))
}

/// What the Decision provider page and the Experimental switch render; the shape is the contract with ui/ai.js.
#[derive(Serialize)]
pub struct State {
    presets: &'static [Preset],
    preset: &'static str,
    wire: Wire,
    base_url: String,
    model: String,
    has_key: bool,
    triage: bool,
    problem: Option<&'static str>,
    /// Whether a question would leave this Mac; drives the "sends text off this Mac" pill.
    off_device: bool,
    laya: laya::Status,
}

#[tauri::command(async)]
pub fn decision_state(app: AppHandle) -> State {
    let db = app.state::<Db>();
    let c = Config::load(&db.0);
    let laya = app.state::<laya::Laya>();
    let triage = ai::enabled(&db.0.lock().unwrap(), "triage");
    State {
        presets: PRESETS,
        preset: c.preset.id,
        wire: c.wire,
        has_key: c.key.is_some(),
        triage,
        problem: c.problem(laya.installed()),
        off_device: c.off_device(),
        laya: laya.status(),
        model: c.model,
        base_url: c.base_url,
    }
}

/// An empty key removes it.
#[tauri::command(async)]
pub fn decision_set_key(preset: String, key: String) -> Result<(), String> {
    let id = account(PRESETS.iter().find(|p| p.id == preset && p.id != "laya").ok_or("unknown preset")?.id);
    match key.trim() {
        "" => keychain::remove(&id),
        key => keychain::set(&id, key),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ai::stub;

    fn config(id: &str, base_url: &str) -> Config {
        Config { preset: preset(Some(id)), wire: preset(Some(id)).wire, base_url: base_url.into(), model: String::new(), key: None }
    }

    fn reply(body: &str) -> (u16, String) {
        (200, body.into())
    }

    #[test]
    fn the_jev_adapter_posts_the_question_with_the_key_and_reads_the_choice() {
        let (base, seen) = stub::serve(vec![reply(r#"{"choice":"Yes"}"#), reply(r#"{"choice":"no"}"#)]);
        let p = adapter(Wire::Jev, &base, Some("k-1".into()), "");
        assert_eq!(p.decide("Q?", "ctx"), Ok(true));
        assert_eq!(p.decide("Q?", "ctx"), Ok(false));
        let req = seen.recv().unwrap();
        assert_eq!(req.path, "/v1/decide");
        assert!(req.head.to_lowercase().contains("authorization: bearer k-1"));
        let body: Value = serde_json::from_str(&req.body).unwrap();
        assert_eq!((body["question"].as_str(), body["context"].as_str(), body["choices"][1].as_str()), (Some("Q?"), Some("ctx"), Some("no")));
    }

    #[test]
    fn the_openai_adapter_sends_the_model_and_reads_the_nested_decision() {
        let (base, seen) = stub::serve(vec![reply(r#"{"decision":{"choice":"yes"}}"#)]);
        let p = adapter(Wire::Openai, &format!("{base}/"), Some("sk".into()), "gpt-x");
        assert_eq!(p.decide("Q?", "ctx"), Ok(true));
        let req = seen.recv().unwrap();
        assert_eq!(req.path, "/v1/decisions");
        let body: Value = serde_json::from_str(&req.body).unwrap();
        assert_eq!((body["model"].as_str(), body["input"].as_str()), (Some("gpt-x"), Some("Q?\n\nctx")));
    }

    #[test]
    fn an_unclear_answer_or_a_failure_is_an_error_never_a_yes() {
        let (base, _seen) = stub::serve(vec![reply(r#"{"choice":"maybe"}"#), reply("{}"), (401, r#"{"error":{"message":"bad key"}}"#.into())]);
        let p = adapter(Wire::Jev, &base, Some("sk-secret".into()), "");
        assert!(p.decide("q", "c").unwrap_err().contains("not yes or no"));
        assert!(p.decide("q", "c").is_err());
        let e = p.decide("q", "c").unwrap_err();
        assert_eq!(e, "The decision provider answered 401: bad key");
        assert!(!e.contains("sk-secret"));
    }

    #[test]
    fn only_hosted_and_remote_presets_are_off_device_and_laya_never_is() {
        assert!(!config("laya", "").off_device());
        assert!(!config("laya", "https://example.com").off_device()); // the address is never used for Laya
        assert!(config("jev", PRESETS[1].base_url).off_device());
        assert!(config("openai", PRESETS[2].base_url).off_device());
        assert!(!config("custom", "http://127.0.0.1:8000/v1").off_device());
        assert!(config("custom", "http://10.0.0.5:8000/v1").off_device());
    }

    #[test]
    fn what_is_missing_is_named_per_preset() {
        let mut c = config("laya", "");
        assert!(c.problem(false).unwrap().contains("Set up Laya"));
        assert_eq!(c.problem(true), None); // its key is generated, not typed
        c = config("jev", PRESETS[1].base_url);
        assert!(c.problem(true).unwrap().contains("API key"));
        c.key = Some("k".into());
        assert_eq!(c.problem(true), None);
        c = config("openai", PRESETS[2].base_url);
        c.key = Some("k".into());
        assert!(c.problem(true).unwrap().contains("model"));
        c.model = "m".into();
        assert_eq!(c.problem(true), None);
        assert_eq!(config("custom", "http://localhost:8000/v1").problem(true), None); // a local server needs no key
        assert!(config("custom", "nope").problem(true).unwrap().contains("base URL"));
    }

    #[test]
    fn settings_pick_the_preset_and_a_custom_server_picks_its_wire() {
        let db = stub::db();
        assert_eq!(Config::from_settings(&db).preset.id, "laya");
        settings::set(&db, "decision_preset", "custom").unwrap();
        settings::set(&db, "decision_wire", "openai").unwrap();
        settings::set(&db, "decision_base_url", "http://localhost:9/v1").unwrap();
        let c = Config::from_settings(&db);
        assert_eq!((c.wire, c.base_url.as_str()), (Wire::Openai, "http://localhost:9/v1"));
        settings::set(&db, "decision_preset", "jev").unwrap(); // a stale wire setting never changes a fixed preset
        assert_eq!(Config::from_settings(&db).wire, Wire::Jev);
    }
}
